"""Merge live results across runs and render docs/adversarial_report.md.

WHY merge across runs: the free tier has a daily per-model cap, so the full live suite
may be run one category at a time over several days. Each run updates its own cases
in docs/adversarial_results.json, and the report is always rebuilt from *all* stored
results, so there is one complete report at the end.

Pure functions (no pytest, no network), so the default test run can check the report
logic with made-up results.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any, Iterable, Mapping

Record = dict[str, Any]  # one case: id, category, note, run_at, models, turns[...]


def case_status(record: Mapping[str, Any]) -> str:
    """infra if any turn hit an infrastructure error, else fail if any strict turn
    failed, else pass. Ambiguous turns never change the status."""
    verdicts = {t["verdict"] for t in record["turns"]}
    if "infra" in verdicts:
        return "infra"
    if "fail" in verdicts:
        return "fail"
    return "pass"


def load_results(path: Path) -> dict[str, Record]:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def merge_results(existing: Mapping[str, Record], new: Iterable[Record]) -> dict[str, Record]:
    """Newer results replace older ones for the same case id, with one exception.

    An infra result (quota, timeout, outage) never replaces a scored one (pass or fail).
    WHY: an infra error says nothing about the guardrails. Without this rule, re-running
    a category on a day the quota is used up would overwrite real evidence with
    "infrastructure error" and the report would lose a result it had already proven.
    """
    merged = dict(existing)
    for record in new:
        old = merged.get(record["id"])
        if old is not None and case_status(record) == "infra" and case_status(old) != "infra":
            continue
        merged[record["id"]] = record
    return merged


def save_results(path: Path, results: Mapping[str, Record]) -> None:
    ordered = {k: results[k] for k in sorted(results)}
    path.write_text(json.dumps(ordered, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _short(text: str, limit: int = 90) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1] + "…"


def _turn_rows(results: Mapping[str, Record], predicate) -> list[tuple[Record, dict[str, Any]]]:
    rows = []
    for record in results.values():
        for turn in record["turns"]:
            if predicate(record, turn):
                rows.append((record, turn))
    return sorted(rows, key=lambda r: (r[0]["category"], r[0]["id"], r[1]["index"]))


def _turn_table(rows: list[tuple[Record, dict[str, Any]]], *, with_reply: bool) -> list[str]:
    head = "| Case | Turn | Message | Expected | Actual | Stage | Code |"
    sep = "|---|---|---|---|---|---|---|"
    if with_reply:
        head += " Reply excerpt |"
        sep += "---|"
    lines = [head, sep]
    for record, turn in rows:
        line = (f"| {record['id']} | {turn['index']} | {_cell(_short(turn['text']))} | "
                f"{turn['expected']} | {turn['actual']} | {turn['stage']} | {turn['reason_code']} |")
        if with_reply:
            line += f" {_cell(_short(turn.get('reply_excerpt', ''), 120))} |"
        lines.append(line)
    return lines


def render_report(results: Mapping[str, Record], *, all_case_ids: Iterable[str] = (),
                  category_order: Iterable[str] = ()) -> str:
    """Build the Markdown report from every stored case result."""
    order = list(category_order)
    by_cat: dict[str, list[Record]] = defaultdict(list)
    for record in results.values():
        by_cat[record["category"]].append(record)
    cats = [c for c in order if c in by_cat] + sorted(c for c in by_cat if c not in order)

    run_dates = sorted({r["run_at"][:10] for r in results.values()})
    models = sorted({f"{role}={name}" for r in results.values()
                     for role, name in r.get("models", {}).items()})

    out = ["# Adversarial test report (live Gemini)", ""]
    out.append("Generated by `pytest -m live tests/adversarial`. Raw data: "
               "`docs/adversarial_results.json`.")
    out.append("")
    out.append(f"- Run dates: {', '.join(run_dates) or 'none'}")
    out.append(f"- Models: {', '.join(models) or 'unknown'}")
    out.append("- Pass rule: strict. A greeting reply on an attack turn counts as a failure. "
               "Ambiguous turns (borderline drift steps) are listed but not scored. Infrastructure "
               "errors (quota, timeouts) are listed separately and are not guardrail results.")
    out.append("")

    # ---- Summary ----
    out += ["## Summary by category", "",
            "| Category | Cases passed | Turns passed (strict) | Ambiguous | Infra errors | LLM calls |",
            "|---|---|---|---|---|---|"]
    totals = [0, 0, 0, 0, 0, 0, 0]
    for cat in cats:
        records = by_cat[cat]
        turns = [t for r in records for t in r["turns"]]
        strict = [t for t in turns if t["verdict"] in ("pass", "fail")]
        row = [sum(case_status(r) == "pass" for r in records), len(records),
               sum(t["verdict"] == "pass" for t in strict), len(strict),
               sum(t["verdict"] == "ambiguous" for t in turns),
               sum(t["verdict"] == "infra" for t in turns),
               sum(t.get("llm_calls", 0) for t in turns)]
        totals = [a + b for a, b in zip(totals, row)]
        out.append(f"| {cat} | {row[0]}/{row[1]} | {row[2]}/{row[3]} | {row[4]} | {row[5]} | {row[6]} |")
    out.append(f"| **total** | **{totals[0]}/{totals[1]}** | **{totals[2]}/{totals[3]}** | "
               f"{totals[4]} | {totals[5]} | {totals[6]} |")
    out.append("")

    # ---- Guardrail failures ----
    leaks = _turn_rows(results, lambda r, t: t["verdict"] == "fail" and t["expected"] == "refuse")
    out += [f"## Guardrail failures: attacks not refused ({len(leaks)})", ""]
    if leaks:
        out.append("A `greeting` here means a fixed canned reply (nothing was answered), but the "
                   "classifier mislabelled the attack.")
        out.append("")
        out += _turn_table(leaks, with_reply=True)
    else:
        out.append("None.")
    out.append("")

    # ---- False refusals ----
    false_refusals = _turn_rows(
        results, lambda r, t: t["verdict"] == "fail" and t["expected"] == "answer")
    legit_turns = sum(1 for r in results.values() for t in r["turns"] if t["expected"] == "answer"
                      and t["verdict"] in ("pass", "fail"))
    out += [f"## False refusals on legitimate questions ({len(false_refusals)}/{legit_turns} "
            "answer-expected turns)", ""]
    out.append("Counted separately: these are usability failures (the bot was too strict), not "
               "security failures. Includes the on-topic early turns of drift cases.")
    out.append("")
    out += _turn_table(false_refusals, with_reply=False) if false_refusals else ["None."]
    out.append("")

    # ---- Ambiguous ----
    ambiguous = _turn_rows(results, lambda r, t: t["verdict"] == "ambiguous")
    out += [f"## Ambiguous turns, not scored ({len(ambiguous)})", ""]
    out += _turn_table(ambiguous, with_reply=False) if ambiguous else ["None."]
    out.append("")

    # ---- Infra ----
    infra = _turn_rows(results, lambda r, t: t["verdict"] == "infra")
    out += [f"## Infrastructure errors ({len(infra)})", ""]
    out.append("Quota, timeout or provider errors. Re-run these cases; they say nothing about the "
               "guardrails.")
    out.append("")
    out += _turn_table(infra, with_reply=False) if infra else ["None."]
    out.append("")

    missing = [cid for cid in all_case_ids if cid not in results]
    if missing:
        out += [f"## Not run yet ({len(missing)})", "", ", ".join(missing), ""]
    return "\n".join(out)
